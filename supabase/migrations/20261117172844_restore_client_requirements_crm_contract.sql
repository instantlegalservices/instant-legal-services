-- Restore the missing TEST compatibility contract for the existing ILS lead/CRM table.
-- Production already owns this table; CREATE TABLE IF NOT EXISTS is intentionally a no-op there.
-- Preserve the historical "Souce" column spelling used by existing deployments.
create table if not exists public.client_requirements (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  client_name text,
  legal_matter text,
  brief_requirement text,
  status text default 'New',
  "Souce" text default 'Website',
  state text,
  district_city text,
  mobile text,
  assigned_advocate text,
  payment_status text default 'Pending',
  follow_up_date date,
  internal_notes text,
  priority text default 'Normal',
  assigned_advocate_id bigint,
  release_advocate_contact boolean not null default false,
  contact_released_at timestamptz,
  client_access_token text unique,
  client_access_created_at timestamptz,
  client_access_expires_at timestamptz
);

-- Refuse to continue against an unexpected partial table instead of silently masking drift.
do $$
declare
  required_columns text[] := array[
    'id','created_at','client_name','legal_matter','brief_requirement','status',
    'Souce','state','district_city','mobile','assigned_advocate','payment_status',
    'follow_up_date','internal_notes','priority','assigned_advocate_id',
    'release_advocate_contact','contact_released_at','client_access_token',
    'client_access_created_at','client_access_expires_at'
  ];
  missing_columns text[];
begin
  select array_agg(required.column_name)
    into missing_columns
  from unnest(required_columns) as required(column_name)
  where not exists (
    select 1 from information_schema.columns c
    where c.table_schema='public'
      and c.table_name='client_requirements'
      and c.column_name=required.column_name
  );
  if coalesce(array_length(missing_columns,1),0) > 0 then
    raise exception 'client_requirements compatibility check failed; missing columns: %', missing_columns;
  end if;
end $$;

-- Preserve the existing customer-to-lead relationship where the TEST profile table exists.
do $$
begin
  if to_regclass('public.customer_profiles') is not null
     and exists (
       select 1 from information_schema.columns
       where table_schema='public' and table_name='customer_profiles'
         and column_name='client_requirement_id' and data_type='bigint'
     )
     and not exists (
       select 1 from pg_constraint
       where conrelid='public.customer_profiles'::regclass
         and conname='customer_profiles_client_requirement_id_fkey'
     ) then
    alter table public.customer_profiles
      add constraint customer_profiles_client_requirement_id_fkey
      foreign key (client_requirement_id)
      references public.client_requirements(id)
      on delete set null;
  end if;
end $$;

create index if not exists idx_client_requirements_access_token
  on public.client_requirements(client_access_token);
create index if not exists idx_client_requirements_assigned_advocate
  on public.client_requirements(assigned_advocate_id);
create index if not exists idx_ils_client_status_priority
  on public.client_requirements(status, priority);

alter table public.client_requirements enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='client_requirements'
      and policyname='ils_admin_client_requirements_all'
  ) then
    create policy ils_admin_client_requirements_all
      on public.client_requirements for all to authenticated
      using (public.ils_is_admin())
      with check (public.ils_is_admin());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='client_requirements'
      and policyname='ils_v12_public_client_requirement_insert'
  ) then
    create policy ils_v12_public_client_requirement_insert
      on public.client_requirements for insert to anon, authenticated
      with check (
        length(trim(coalesce(client_name,''))) between 1 and 100
        and mobile ~ '^[0-9]{10}$'
        and length(trim(coalesce(brief_requirement,''))) between 1 and 3000
      );
  end if;
end $$;

grant insert on public.client_requirements to anon;
grant select, insert, update, delete on public.client_requirements to authenticated;
