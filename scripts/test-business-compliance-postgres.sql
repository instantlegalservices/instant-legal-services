CREATE OR REPLACE FUNCTION public.get_client_portal(text, text)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN (
    SELECT jsonb_build_object(
      'primary_mobile', (
        SELECT case when coalesce(c.release_advocate_contact, false) then ar.mobile else null end
        FROM public.client_requirements c
        JOIN public.advocate_assignments aa ON aa.lead_id = c.id
        JOIN public.advocate_registrations ar ON ar.id = aa.advocate_id
        where aa.lead_id = c.id
              and aa.status in ('Assigned','Active')

            order by aa.assigned_at asc
        LIMIT 1
      ),
      'secondary_mobile', (
        SELECT case when coalesce(c.release_advocate_contact, false) then ar.mobile else null end
        FROM public.client_requirements c
        JOIN public.advocate_assignments aa ON aa.lead_id = c.id
        JOIN public.advocate_registrations ar ON ar.id = aa.advocate_id
        where aa.lead_id = c.id
              and aa.status in ('Assigned','Active')
        ORDER BY aa.assigned_at asc
        LIMIT 1
      )
    )
  );
END;
$$;

