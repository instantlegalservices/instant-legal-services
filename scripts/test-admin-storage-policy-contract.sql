CREATE SCHEMA auth;
CREATE SCHEMA storage;
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
CREATE OR REPLACE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object('email', current_setting('request.jwt.claim.email', true))
$$;
CREATE OR REPLACE FUNCTION storage.foldername(name text) RETURNS text[]
LANGUAGE sql IMMUTABLE AS $$
  SELECT string_to_array(name, '/')[1:array_length(string_to_array(name, '/'),1)-1]
$$;
GRANT USAGE ON SCHEMA auth, storage TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid(), auth.jwt(), storage.foldername(text) TO anon, authenticated, service_role;

CREATE TABLE public.ils_admin_users(user_id uuid PRIMARY KEY, email text, created_at timestamptz NOT NULL DEFAULT now());
CREATE OR REPLACE FUNCTION public.ils_is_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT EXISTS (SELECT 1 FROM public.ils_admin_users WHERE user_id = auth.uid())
$$;
GRANT EXECUTE ON FUNCTION public.ils_is_admin() TO authenticated, service_role;

