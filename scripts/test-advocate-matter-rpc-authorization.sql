-- These fixture RPCs preserve the live signatures and the exact reviewed legacy identity
-- block/active-assignment check. Their minimal bodies isolate the auth contract only.
CREATE OR REPLACE FUNCTION public.get_advocate_client_portal(p_client_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE
    v_email text := lower(trim(auth.jwt()->>'email'));
    a record;
    c record;
BEGIN
    select *
    into a
    from public.advocate_registrations
    where coalesce(verification_status,status,'Pending') = 'Approved'
      and (
          auth_user_id = auth.uid()
          or lower(trim(email)) = v_email
      )
    limit 1;

    if not found then
        raise exception 'Not authorized';
    end if;

    if not exists (
        select 1
        from public.advocate_assignments
        where lead_id = p_client_id
          and advocate_id = a.id
          and status in ('Assigned','Active')
    ) then
        raise exception 'This matter is not assigned to you';
    end if;

    return jsonb_build_object('advocate_id', a.id);
END
$function$;

